PROMPT === 3. SQL QUERIES: JOIN, AGGREGATION, GROUPING, SUBQUERY ===

-- JOIN: visits with patient and doctor details.
SELECT v.visit_id, p.patient_name, d.doctor_name, d.department, v.visit_status
FROM visit v
JOIN patient p ON p.patient_id = v.patient_id
JOIN doctor d ON d.doctor_id = v.doctor_id
ORDER BY v.visit_id;

-- GROUP BY + aggregate: visit count by department.
SELECT d.department, COUNT(v.visit_id) AS total_visits,
       AVG(d.consultation_fee) AS average_fee
FROM doctor d LEFT JOIN visit v ON v.doctor_id = d.doctor_id
GROUP BY d.department
ORDER BY total_visits DESC;

-- Subquery: doctors whose fee is above the overall average.
SELECT doctor_name, consultation_fee
FROM doctor
WHERE consultation_fee > (SELECT AVG(consultation_fee) FROM doctor);

-- Join + aggregate: medicine cost for each visit.
SELECT v.visit_id, p.patient_name,
       NVL(SUM(pr.quantity * m.price_per_unit), 0) AS medicine_cost
FROM visit v
JOIN patient p ON p.patient_id = v.patient_id
LEFT JOIN prescription pr ON pr.visit_id = v.visit_id
LEFT JOIN medicine m ON m.medicine_id = pr.medicine_id
GROUP BY v.visit_id, p.patient_name
ORDER BY v.visit_id;

PROMPT === 4. FUNCTION: CALCULATE MEDICINE COST FOR A VISIT ===

CREATE OR REPLACE FUNCTION fn_medicine_cost (p_visit_id IN NUMBER)
RETURN NUMBER
IS
    v_cost NUMBER(10,2);
BEGIN
    SELECT NVL(SUM(pr.quantity * m.price_per_unit), 0)
      INTO v_cost
      FROM prescription pr
      JOIN medicine m ON m.medicine_id = pr.medicine_id
     WHERE pr.visit_id = p_visit_id;
    RETURN v_cost;
END;
/

SELECT 301 AS visit_id, fn_medicine_cost(301) AS medicine_cost FROM dual;

PROMPT === 5. PROCEDURE: BOOK AN APPOINTMENT ===

CREATE OR REPLACE PROCEDURE sp_book_appointment (
    p_visit_id IN NUMBER,
    p_patient_id IN NUMBER,
    p_doctor_id IN NUMBER
)
IS
BEGIN
    INSERT INTO visit (visit_id, patient_id, doctor_id, visit_datetime, visit_type, visit_status)
    VALUES (p_visit_id, p_patient_id, p_doctor_id, SYSTIMESTAMP, 'Appointment', 'Scheduled');
    DBMS_OUTPUT.PUT_LINE('Appointment booked. Visit ID: ' || p_visit_id);
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20001, 'Visit ID already exists.');
    WHEN OTHERS THEN
        RAISE;
END;
/

-- Demonstrate the procedure with a new visit.
BEGIN
    sp_book_appointment(304, 1, 102);
END;
