PROMPT === 6. CURSOR: DISPLAY SCHEDULED VISITS ===

DECLARE
    CURSOR c_scheduled_visits IS
        SELECT v.visit_id, p.patient_name, d.doctor_name
        FROM visit v
        JOIN patient p ON p.patient_id = v.patient_id
        JOIN doctor d ON d.doctor_id = v.doctor_id
        WHERE v.visit_status = 'Scheduled'
        ORDER BY v.visit_datetime;
    v_visit_id visit.visit_id%TYPE;
    v_patient  patient.patient_name%TYPE;
    v_doctor   doctor.doctor_name%TYPE;
BEGIN
    OPEN c_scheduled_visits;
    LOOP
        FETCH c_scheduled_visits INTO v_visit_id, v_patient, v_doctor;
        EXIT WHEN c_scheduled_visits%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('Visit ' || v_visit_id || ': ' || v_patient || ' with ' || v_doctor);
    END LOOP;
    CLOSE c_scheduled_visits;
END;
/

PROMPT === 7. TRIGGERS: AUDIT VISITS AND REDUCE MEDICINE STOCK ===

-- Audit INSERT/UPDATE/DELETE actions on visit.
CREATE OR REPLACE TRIGGER trg_visit_audit
AFTER INSERT OR UPDATE OR DELETE ON visit
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO audit_log (table_name, action_type, record_id)
        VALUES ('VISIT', 'INSERT', :NEW.visit_id);
    ELSIF UPDATING THEN
        INSERT INTO audit_log (table_name, action_type, record_id)
        VALUES ('VISIT', 'UPDATE', :NEW.visit_id);
    ELSIF DELETING THEN
        INSERT INTO audit_log (table_name, action_type, record_id)
        VALUES ('VISIT', 'DELETE', :OLD.visit_id);
    END IF;
END;
/

-- Reduce stock automatically when a prescription is inserted; reject insufficient stock.
CREATE OR REPLACE TRIGGER trg_prescription_stock
BEFORE INSERT ON prescription
FOR EACH ROW
DECLARE
    v_stock medicine.stock_quantity%TYPE;
BEGIN
    SELECT stock_quantity INTO v_stock
    FROM medicine
    WHERE medicine_id = :NEW.medicine_id
    FOR UPDATE;

    IF v_stock < :NEW.quantity THEN
        RAISE_APPLICATION_ERROR(-20002, 'Insufficient medicine stock.');
    END IF;

    UPDATE medicine
    SET stock_quantity = stock_quantity - :NEW.quantity
    WHERE medicine_id = :NEW.medicine_id;
END;
/

