PROMPT === 1. DDL AND CONSTRAINTS ===

CREATE TABLE patient (
    patient_id   NUMBER        CONSTRAINT pk_patient PRIMARY KEY,
    patient_name VARCHAR2(50)  NOT NULL,
    phone        VARCHAR2(10)  CONSTRAINT uq_patient_phone UNIQUE NOT NULL,
    gender       VARCHAR2(10)  CONSTRAINT chk_patient_gender CHECK (gender IN ('Male','Female','Other')),
    blood_group  VARCHAR2(3),
    CONSTRAINT chk_patient_blood CHECK (blood_group IN ('A+','A-','B+','B-','AB+','AB-','O+','O-'))
);

CREATE TABLE doctor (
    doctor_id        NUMBER        CONSTRAINT pk_doctor PRIMARY KEY,
    doctor_name      VARCHAR2(50)  NOT NULL,
    department       VARCHAR2(30)  NOT NULL,
    consultation_fee NUMBER(8,2)  CONSTRAINT chk_doctor_fee CHECK (consultation_fee > 0)
);

CREATE TABLE medicine (
    medicine_id    NUMBER        CONSTRAINT pk_medicine PRIMARY KEY,
    medicine_name  VARCHAR2(50)  NOT NULL,
    price_per_unit NUMBER(8,2)  CONSTRAINT chk_medicine_price CHECK (price_per_unit > 0),
    stock_quantity NUMBER        DEFAULT 0 CONSTRAINT chk_medicine_stock CHECK (stock_quantity >= 0)
);

CREATE TABLE visit (
    visit_id       NUMBER        CONSTRAINT pk_visit PRIMARY KEY,
    patient_id     NUMBER        NOT NULL,
    doctor_id      NUMBER        NOT NULL,
    visit_datetime TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    visit_type     VARCHAR2(15)  CONSTRAINT chk_visit_type CHECK (visit_type IN ('Appointment','Emergency')),
    visit_status   VARCHAR2(15)  DEFAULT 'Scheduled' NOT NULL,
    CONSTRAINT fk_visit_patient FOREIGN KEY (patient_id) REFERENCES patient(patient_id),
    CONSTRAINT fk_visit_doctor  FOREIGN KEY (doctor_id) REFERENCES doctor(doctor_id),
    CONSTRAINT chk_visit_status CHECK (visit_status IN ('Scheduled','Under Treatment','Completed','Cancelled'))
);

CREATE TABLE prescription (
    prescription_id NUMBER CONSTRAINT pk_prescription PRIMARY KEY,
    visit_id        NUMBER NOT NULL,
    medicine_id     NUMBER NOT NULL,
    quantity        NUMBER NOT NULL CONSTRAINT chk_prescription_qty CHECK (quantity > 0),
    CONSTRAINT fk_prescription_visit FOREIGN KEY (visit_id) REFERENCES visit(visit_id),
    CONSTRAINT fk_prescription_medicine FOREIGN KEY (medicine_id) REFERENCES medicine(medicine_id)
);

CREATE TABLE audit_log (
    log_id      NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_audit_log PRIMARY KEY,
    table_name  VARCHAR2(30) NOT NULL,
    action_type VARCHAR2(10) NOT NULL,
    record_id   NUMBER,
    changed_at  TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT chk_audit_action CHECK (action_type IN ('INSERT','UPDATE','DELETE'))
);

